-- backend/src/main/resources/db/migration/V58__chat_title_lifecycle.sql
--
-- SafeAI Desk V58: deterministic chat-title lifecycle.
--
-- Adds title provenance so an automatic first-message title can never
-- overwrite a title explicitly chosen by the user.
--
-- title_source:
--   DEFAULT - new empty chat with the canonical "Новый чат" title;
--   AUTO    - title generated once from the first accepted USER message;
--   USER    - title explicitly supplied or renamed by the user.
--
-- Automatic naming is deterministic and does not perform an additional
-- provider/LLM call.
--
-- IMPORTANT:
-- After this migration has been applied by Flyway, do not edit this file.

DO $migration$
BEGIN
    IF to_regclass('public.chat_sessions') IS NULL THEN
        RAISE EXCEPTION
            'V58 requires public.chat_sessions';
    END IF;

    IF to_regclass('public.chat_messages') IS NULL THEN
        RAISE EXCEPTION
            'V58 requires public.chat_messages';
    END IF;

    IF to_regclass('public.audit_event_types') IS NULL THEN
        RAISE EXCEPTION
            'V58 requires public.audit_event_types';
    END IF;
END
$migration$;


-- Keep DEFAULT 'USER' for rolling-deployment safety.
-- An older backend node does not know title_source. Therefore a title written
-- by such a node must be treated as user-owned and must never become eligible
-- for a later automatic overwrite.
ALTER TABLE public.chat_sessions
    ADD COLUMN title_source varchar(16) DEFAULT 'USER';


-- Normalize null/blank legacy titles before enforcing the new invariant.
UPDATE public.chat_sessions
SET title = 'Новый чат'
WHERE title IS NULL
   OR btrim(title) = '';


-- Existing UI-created chats commonly have the placeholder "Новый чат".
--
-- For chats that already contain USER messages, derive a useful historical
-- title from the first USER message so the chat list becomes navigable
-- immediately after deployment.
--
-- Historical backfill is intentionally deterministic and does not invoke AI.
WITH first_user_message AS (
    SELECT DISTINCT ON (message.session_id)
           message.session_id,
           regexp_replace(
               btrim(message.content),
               '[[:space:]]+',
               ' ',
               'g'
           ) AS normalized_content
    FROM public.chat_messages message
    WHERE message.role = 'USER'
      AND btrim(message.content) <> ''
    ORDER BY
        message.session_id,
        message.created_at,
        message.id
),
legacy_default_chat AS (
    SELECT
        session.id,
        CASE
            WHEN char_length(first_user.normalized_content) <= 72
                THEN first_user.normalized_content
            ELSE
                rtrim(
                    left(
                        first_user.normalized_content,
                        71
                    )
                ) || '…'
        END AS generated_title
    FROM public.chat_sessions session
    JOIN first_user_message first_user
      ON first_user.session_id = session.id
    WHERE session.title = 'Новый чат'
)
UPDATE public.chat_sessions session
SET
    title = legacy.generated_title,
    title_source = 'AUTO'
FROM legacy_default_chat legacy
WHERE session.id = legacy.id;


-- Empty historical placeholder chats remain eligible for first-message
-- automatic naming.
--
-- Historical non-placeholder titles are conservatively treated as USER-owned:
-- without provenance it is unsafe to assume they may be overwritten.
UPDATE public.chat_sessions
SET title_source = CASE
    WHEN title = 'Новый чат'
        THEN 'DEFAULT'
    WHEN title_source = 'AUTO'
        THEN 'AUTO'
    ELSE 'USER'
END;


ALTER TABLE public.chat_sessions
    ALTER COLUMN title SET NOT NULL,
    ALTER COLUMN title_source SET NOT NULL;


-- Only the three explicitly supported provenance states are valid.
ALTER TABLE public.chat_sessions
    ADD CONSTRAINT chk_chat_sessions_title_source_v58
    CHECK (
        title_source IN (
            'DEFAULT',
            'AUTO',
            'USER'
        )
    )
    NOT VALID;

ALTER TABLE public.chat_sessions
    VALIDATE CONSTRAINT chk_chat_sessions_title_source_v58;


-- Persisted titles must always contain meaningful text and stay within the
-- existing application/storage limit.
ALTER TABLE public.chat_sessions
    ADD CONSTRAINT chk_chat_sessions_title_non_blank_v58
    CHECK (
        char_length(
            btrim(title)
        ) BETWEEN 1 AND 255
    )
    NOT VALID;

ALTER TABLE public.chat_sessions
    VALIDATE CONSTRAINT chk_chat_sessions_title_non_blank_v58;


-- DEFAULT has one canonical representation. This prevents future code or
-- direct SQL from producing DEFAULT provenance with an arbitrary title.
ALTER TABLE public.chat_sessions
    ADD CONSTRAINT chk_chat_sessions_default_title_v58
    CHECK (
        title_source <> 'DEFAULT'
        OR title = 'Новый чат'
    )
    NOT VALID;

ALTER TABLE public.chat_sessions
    VALIDATE CONSTRAINT chk_chat_sessions_default_title_v58;


COMMENT ON COLUMN public.chat_sessions.title_source IS
    'DEFAULT=new empty chat; AUTO=derived once from first accepted USER message; USER=explicit user title';


-- Manual rename is an auditable user action.
-- ChatTitleService records metadata about the rename but deliberately does not
-- copy the title text itself into audit details.
INSERT INTO public.audit_event_types (
    name,
    description
)
VALUES (
    'CHAT_RENAMED',
    'Chat session renamed by its owner'
)
ON CONFLICT (name) DO NOTHING;